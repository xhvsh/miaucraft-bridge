package com.xhvsh.miaucraftbridge;

import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.security.KeyFactory;
import java.security.PublicKey;
import java.security.Signature;
import java.security.spec.X509EncodedKeySpec;
import java.util.Base64;

/**
 * Authenticity check for self-updates.
 *
 * <p>The manifest's sha256 only proves the jar matches the manifest; both come
 * from the same GitHub repository, so anyone who can push there (a stolen
 * token, a compromised CI job) could ship a jar that runs with full server
 * privileges. The manifest therefore also carries an Ed25519 signature over
 * {@code (version, sha256)} made with a private key that never leaves the
 * maintainer's machine; the matching public key is compiled in here.
 *
 * <p>The signed message binds the version to the digest, so a signature cannot
 * be re-used to publish a different jar under the same version.
 */
final class UpdateSignature {

  /**
   * X.509 (SubjectPublicKeyInfo) Ed25519 public key, Base64. Generated by
   * {@code java dev/ReleaseSigner.java gen}. Rotating it means shipping a
   * release signed by the OLD key that contains the new one.
   */
  static final String RELEASE_PUBLIC_KEY = "MCowBQYDK2VwAyEAzLFX/8UMIPaiO4AFa5yJb93KDmgnSgkffeJcdLuT2ds=";

  private static final String DOMAIN = "miaucraft-bridge-update-v1";

  private UpdateSignature() {
  }

  /** Exact bytes that are signed; the release tooling builds the same string. */
  static byte[] message(String version, String sha256) {
    String text = DOMAIN + "\n" + version.trim() + "\n" + sha256.trim().toLowerCase(java.util.Locale.ROOT) + "\n";
    return text.getBytes(StandardCharsets.UTF_8);
  }

  static PublicKey parsePublicKey(String base64) throws GeneralSecurityException {
    byte[] der = Base64.getDecoder().decode(base64.trim());
    return KeyFactory.getInstance("Ed25519").generatePublic(new X509EncodedKeySpec(der));
  }

  /** True only for a well-formed signature that verifies; never throws. */
  static boolean verify(PublicKey key, String version, String sha256, String signatureBase64) {
    if (key == null || version == null || sha256 == null || signatureBase64 == null) return false;
    try {
      byte[] sig = Base64.getDecoder().decode(signatureBase64.trim());
      Signature verifier = Signature.getInstance("Ed25519");
      verifier.initVerify(key);
      verifier.update(message(version, sha256));
      return verifier.verify(sig);
    } catch (GeneralSecurityException | IllegalArgumentException e) {
      return false;
    }
  }
}
